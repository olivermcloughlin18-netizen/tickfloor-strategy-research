// Emits src/data/examStats.ts: the 29 Sep 2026 "final exam" (robustness battery + one-shot holdout).
// Run: node scripts/research/build-exam-stats.mjs   (chained after build-registry by `npm run research:registry`)
// Sources: research/hunt2/robustness-0929.md (the battery's own generated tables) and
// research/hunt2/holdout-exam-0929.json (runner output). Nothing is typed into a component.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const p = (...s) => join(ROOT, ...s);
const md = readFileSync(p("research/hunt2/robustness-0929.md"), "utf8");
const cells = (l) => l.split("|").slice(1, -1).map((c) => c.trim());
const pp = (s) => { const m = /([+-]?\d+(?:\.\d+)?)pp/.exec(s ?? ""); return m ? Number(m[1]) / 100 : null; };
const section = (title) => md.split(/^#{2,3} /m).find((s) => s.startsWith(title)) ?? "";

const sel = section("Selection (20)").split("\n").filter((l) => /^\| \d+ \|/.test(l)).map(cells)
  .map((c) => ({ rank: Number(c[0]), id: c[1], family: c[2], mode: c[3], assets: Number(c[4]), excess: pp(c[5]) }));
const bat = section("Battery per strategy").split("\n").filter((l) => /^\| [a-z0-9-]+ \| ok \|/.test(l)).map(cells);
const surv = section("Survivors, most robust first").split("\n").map((l) => /^\d+\. (\S+) \(.*worst-case ([+-][\d.]+)pp\/yr/.exec(l)).filter(Boolean)
  .map((m) => ({ id: m[1], worst: Number(m[2]) / 100 }));
const failWhy = Object.fromEntries(section("Fail reasons").split("\n").map((l) => /^- (\S+): fails (.*)$/.exec(l)).filter(Boolean).map((m) => [m[1], m[2].replace(/[()]/g, "").split(" ").filter(Boolean)]));
const TEST = { a: "2x costs", b: "drop top asset", "c-": "-25% settings", "c+": "+25% settings", d: "dumb control", e: "exposure-matched hold" };

if (sel.length !== 20 || bat.length !== 20) throw new Error(`robustness-0929.md parse: ${sel.length} selection / ${bat.length} battery rows, expected 20/20`);
const battery = sel.map((s) => {
  const row = bat.find((c) => c[0] === s.id);
  const survives = /SURVIVES/.test(row[9]);
  const w = surv.find((x) => x.id === s.id);
  return { ...s, survives, worstCase: w?.worst ?? null, failed: survives ? [] : (failWhy[s.id] ?? []).map((k) => TEST[k.replace(/^\(|\)$/g, "")] ?? k) };
}).sort((a, b) => Number(b.survives) - Number(a.survives) || (b.worstCase ?? -9) - (a.worstCase ?? -9) || a.rank - b.rank);

const h = JSON.parse(readFileSync(p("research/hunt2/holdout-exam-0929.json"), "utf8"));
const holdout = h.candidates.map((c) => ({
  id: c.id, verdict: c.verdict, excessAnnual: c.strategy.excessAnnual, p: c.strategy.p, cagr: c.strategy.cagr, bhCagr: c.strategy.bhCagr,
  maxDD: c.strategy.maxDD, bhMaxDD: c.strategy.bhMaxDD, controlExcessAnnual: c.dumbControl.excessAnnual, beatsControl: c.dumbControl.strategyBeatsControl,
  firstDay: c.strategy.firstDay, lastDay: c.strategy.lastDay, days: c.strategy.days,
}));
const j = (x) => JSON.stringify(x, null, 2);
writeFileSync(p("src/data/examStats.ts"), `// GENERATED by scripts/research/build-exam-stats.mjs — do not hand-edit.
// Sources: research/hunt2/robustness-0929.md, research/hunt2/holdout-exam-0929.json.

export type BatteryRow = { rank: number; id: string; family: string; mode: string; assets: number; excess: number | null; survives: boolean; worstCase: number | null; failed: string[] };
export type HoldoutRow = { id: string; verdict: string; excessAnnual: number; p: number; cagr: number; bhCagr: number; maxDD: number; bhMaxDD: number; controlExcessAnnual: number; beatsControl: boolean; firstDay: string; lastDay: string; days: number };

export const EXAM_TESTED = ${battery.length};
export const EXAM_SURVIVED = ${battery.filter((r) => r.survives).length};
export const EXAM_BATTERY: BatteryRow[] = ${j(battery)};
export const HOLDOUT_ALPHA = ${h.alpha};
export const HOLDOUT_BOUNDARY = "${h.boundary.slice(0, 10)}";
export const HOLDOUT_CONFIRMED = ${h.candidates.filter((c) => /^CONFIRMED/.test(c.verdict)).length};
export const HOLDOUT: HoldoutRow[] = ${j(holdout)};
`);
console.log(`exam: ${battery.length} tested, ${battery.filter((r) => r.survives).length} survived, holdout ${holdout.map((r) => `${r.id} ${r.verdict}`).join("; ")}`);
